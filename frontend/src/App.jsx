import { useEffect } from "react";
import { Outlet, Route, Routes, useLocation } from "react-router-dom";
import "./App.css";

import Header from "./components/Header";
import FeedPage from "./pages/FeedPage";
import TrendingPage from "./pages/TrendingPage";
import SearchPage from "./pages/SearchPage";
import StoryPage from "./pages/StoryPage";
import { EmptyState } from "./components/States";

function Layout() {
  const { pathname } = useLocation();

  useEffect(() => {
    window.scrollTo(0, 0);
  }, [pathname]);

  return (
    <div className="app">
      <Header />
      <main className="main">
        <Outlet />
      </main>
      <footer className="footer">
        <span>Clarion AI — Stay ahead in the rapidly changing world of AI.</span>
        <p className="footer-note">
          Headlines, summaries and importance scores are generated by AI from
          publishers' RSS feeds and can contain mistakes. Always check the
          original sources linked on each story.
        </p>
      </footer>
    </div>
  );
}

function NotFound() {
  return (
    <EmptyState
      title="Page not found"
      text="That page doesn't exist."
      actionLabel="Back to feed"
      onAction={() => window.location.assign("/")}
    />
  );
}

export default function App() {
  return (
    <Routes>
      <Route element={<Layout />}>
        <Route index element={<FeedPage />} />
        <Route path="trending" element={<TrendingPage />} />
        <Route path="search" element={<SearchPage />} />
        <Route path="stories/:id" element={<StoryPage />} />
        <Route path="*" element={<NotFound />} />
      </Route>
    </Routes>
  );
}